const DICTIONARIES: Record<Locale, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  en,
}

const listeners = new Set<() => void>()
let cachedSetting: LocaleSetting | null = null

function detectSystemLocale(): Locale {
  if (typeof document === 'undefined') return 'zh-CN'
  try {
    const docLang = document.documentElement?.lang?.trim().toLowerCase()
    if (docLang) {
      if (docLang.startsWith('zh')) return 'zh-CN'
      if (docLang.startsWith('en')) return 'en'
    }
    if (typeof navigator !== 'undefined' && typeof navigator.language === 'string') {
      return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
    }
  } catch {
    /* Ignore restricted global access. */
  }
  return 'zh-CN'
}

export function getLocaleSetting(): LocaleSetting {
  if (cachedSetting === null) {
    cachedSetting = loadSettings().locale
  }
  return cachedSetting
}

export function getLocale(): Locale {
  const setting = getLocaleSetting()
  return setting === 'auto' ? detectSystemLocale() : setting
}

export function setLocaleSetting(setting: LocaleSetting): void {
  cachedSetting = setting
  saveSettings({ locale: setting })
  for (const listener of listeners) {
    listener()
  }
}

export function resetLocaleCache(): void {
  cachedSetting = loadSettings().locale
  for (const listener of listeners) {
    listener()
  }
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener)
  return () => { listeners.delete(listener) }
}

/** React hook that re-renders the component whenever the active locale changes. */
export function useLocale(): Locale {
  return useSyncExternalStore(subscribeLocale, getLocale, getLocale)
}

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const dict = DICTIONARIES[getLocale()]
  let text = dict[key] ?? zhCN[key] ?? key
  if (vars !== undefined) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}
